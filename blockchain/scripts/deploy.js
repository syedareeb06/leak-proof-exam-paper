// Deploys ExamPaperVault to the local Hardhat node and registers the demo
// consortium. Usage (two terminals):
//   npx hardhat node
//   npx hardhat run scripts/deploy.js --network localhost
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

const Role = { Custodian: 1, Centre: 2 };

async function main() {
  const signers = await hre.ethers.getSigners();
  const [university] = signers;

  const vault = await hre.ethers.deployContract("ExamPaperVault", [], university);
  await vault.waitForDeployment();
  const address = await vault.getAddress();
  console.log(`ExamPaperVault deployed to ${address} by University ${university.address}`);

  const consortium = [
    [signers[1], Role.Custodian, "Controller of Examinations"],
    [signers[2], Role.Custodian, "State Examination Board"],
    [signers[3], Role.Custodian, "Independent Observer"],
    [signers[4], Role.Centre, "Centre A - City Engineering College"],
    [signers[5], Role.Centre, "Centre B - Govt. Polytechnic Hall"],
    [signers[6], Role.Centre, "Centre C - St. Mary's Institute"],
  ];
  for (const [signer, role, name] of consortium) {
    await (await vault.registerMember(signer.address, role, name)).wait();
    console.log(`  registered ${name.padEnd(38)} ${signer.address}`);
  }

  const { chainId } = await hre.ethers.provider.getNetwork();
  const out = path.join(__dirname, "..", "..", "frontend", "js", "local-deployment.js");
  fs.writeFileSync(
    out,
    `// AUTO-GENERATED by blockchain/scripts/deploy.js\nwindow.LOCAL_DEPLOYMENT = ${JSON.stringify({ address, chainId: Number(chainId) })};\n`
  );
  console.log(`Wrote ${path.relative(process.cwd(), out)} - open the web app and choose "Local Hardhat".`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
