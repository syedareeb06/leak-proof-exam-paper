// Copies the compiled contract (ABI + bytecode) into the web app so the
// frontend can deploy and talk to exactly the same smart contract.
const fs = require("fs");
const path = require("path");

const name = "ExamPaperVault";
const artifact = require(path.join(__dirname, "..", "artifacts", "contracts", `${name}.sol`, `${name}.json`));
const out = path.join(__dirname, "..", "..", "frontend", "js", "contract-artifact.js");

const body = `// AUTO-GENERATED by blockchain/scripts/export-artifact.js - do not edit by hand.
window.CONTRACT_ARTIFACT = ${JSON.stringify({ contractName: name, abi: artifact.abi, bytecode: artifact.bytecode }, null, 2)};
`;
fs.writeFileSync(out, body);
console.log(`Exported ${name} ABI + bytecode to ${path.relative(process.cwd(), out)}`);
